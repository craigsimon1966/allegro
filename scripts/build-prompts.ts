// Compiles prompts/*.md into functions/_lib/prompts.generated.ts so the Pages Functions can use
// them (Workers can't read files at runtime). Run automatically before dev, build and test.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';

export function renderPromptsModule(dir = 'prompts'): string {
  const files = readdirSync(dir)
    .filter((f) => f.endsWith('.md') && f !== 'README.md')
    .sort();
  const entries = files.map(
    (f) =>
      `  ${JSON.stringify(basename(f, '.md'))}: ${JSON.stringify(readFileSync(join(dir, f), 'utf8'))},`,
  );
  return `// Generated by scripts/build-prompts.ts from prompts/*.md. Do not edit by hand.\nexport const PROMPTS: Record<string, string> = {\n${entries.join('\n')}\n};\n`;
}

/**
 * Lists content/units/*.json as static imports in shared/units.generated.ts, so both Vite and
 * the Pages Functions bundler (which has no import.meta.glob) get the same catalogue.
 */
export function renderUnitsModule(dir = 'content/units'): string {
  const files = readdirSync(dir)
    .filter((f) => f.endsWith('.json'))
    .sort();
  const imports = files.map((f, i) => `import u${i} from '../content/units/${f}';`);
  return `// Generated by scripts/build-prompts.ts from content/units/*.json. Do not edit by hand.\nimport type { MicroUnit } from './types';\n${imports.join('\n')}\n\nexport const UNIT_FILES = [${files.map((_, i) => `u${i}`).join(', ')}] as unknown as MicroUnit[];\n`;
}

if (process.argv[1]?.endsWith('build-prompts.ts')) {
  writeFileSync('functions/_lib/prompts.generated.ts', renderPromptsModule());
  writeFileSync('shared/units.generated.ts', renderUnitsModule());
  console.log('prompts compiled');
}
